namespace GcLib;

/// <summary>
/// Total size in bits of a pixel of the image.
/// </summary>
public enum PixelSize
{
    /// <summary>
    /// 1 bit per pixel.
    /// </summary>
    Bpp1 = 1,
    /// <summary>
    /// 2 bits per pixel.
    /// </summary>
    Bpp2 = 2,
    /// <summary>
    /// 4 bits per pixel.
    /// </summary>
    Bpp4 = 4,
    /// <summary>
    /// 8 bits per pixel.
    /// </summary>
    Bpp8 = 8,
    /// <summary>
    /// 10 bits per pixel.
    /// </summary>
    Bpp10 = 10,
    /// <summary>
    /// 12 bits per pixel.
    /// </summary>
    Bpp12 = 12,
    /// <summary>
    /// 14 bits per pixel.
    /// </summary>
    Bpp14 = 14,
    /// <summary>
    /// 16 bits per pixel.
    /// </summary>
    Bpp16 = 16,
    /// <summary>
    /// 32 bits per pixel.
    /// </summary>
    Bpp32 = 32,
    /// <summary>
    /// 64 bits per pixel.
    /// </summary>
    Bpp64 = 64,
    /// <summary>
    /// 96 bits per pixel.
    /// </summary>
    Bpp96 = 96
}
